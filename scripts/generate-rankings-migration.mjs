import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "workers", "rankings", "migrations", "0002_import_legacy.sql");
const SHEET_BASE = "https://docs.google.com/spreadsheets/d/e/2PACX-1vRTQZAN1znMdqJ3eaU_FUtq-UM2HeaOISqqGuTidCE0tCoc8TzA5brhbO-fccCKt-sBOk3pY3Zg0YVW/pub";
const ENDPOINT = "https://script.google.com/macros/s/AKfycby-gmghq1bBK7MakQQ4xjDxK5FbSdoIc9DZcu26bvupWpVo61meNizhcZ-goaLsx2Vn/exec";
const CATALOGS = [
  { type: "games", gid: "1009577165", name: "Game" },
  { type: "movies", gid: "449567167", name: "Movie" },
  { type: "tv", gid: "415412107", name: "Show" },
];

const [catalogRows, mcu, eloResponse, choiceResponse, seedResponse, snapshotResponse, exclusionResponse] = await Promise.all([
  Promise.all(CATALOGS.map(async (catalog) => ({ ...catalog, rows: await loadCsv(`${SHEET_BASE}?single=true&output=csv&gid=${catalog.gid}`) }))),
  JSON.parse(await readFile(path.join(ROOT, "data", "rankings.json"), "utf8")),
  loadJson("listRankingElo"),
  loadJson("listRankingChoices"),
  loadJson("listRankingSeeds"),
  loadJson("listRankingSnapshots"),
  loadJson("listRankingExclusions"),
]);

const lines = ["-- Generated by scripts/generate-rankings-migration.mjs"];
let itemCount = 0;
for (const catalog of catalogRows) {
  for (const row of catalog.rows) {
    const id = clean(row.ID); const name = clean(row[catalog.name]); const rank = number(row.Rank);
    if (!id || !name || !rank) continue;
    lines.push(`INSERT OR REPLACE INTO ranking_items (manager_id, ranking_type, item_id, name, manual_rank, archived) VALUES ('6', ${sql(catalog.type)}, ${sql(id)}, ${sql(name)}, ${rank}, 0);`);
    itemCount += 1;
  }
}

const mcuManagers = new Set(["5", "6", "7"]);
for (const managerId of mcuManagers) for (const item of mcu.items) {
  lines.push(`INSERT OR REPLACE INTO ranking_manual_order (manager_id, ranking_type, item_id, manual_rank) VALUES (${sql(managerId)}, 'mcu', ${sql(item.id)}, ${number(item.rank)});`);
}

const allowed = (managerId, type) => type === "mcu" ? ["5", "6", "7"].includes(managerId) : managerId === "6" && ["games", "movies", "tv"].includes(type);
let eloCount = 0;
const eloGroups = new Set();
for (const row of eloResponse.elo || []) {
  const managerId = field(row, "Manager ID", "managerId"); const type = normalizedType(field(row, "Ranking Type", "rankingType"));
  if (!allowed(managerId, type)) continue;
  eloGroups.add(`${managerId}:${type}`);
  lines.push(`INSERT OR REPLACE INTO ranking_elo (manager_id, ranking_type, item_id, rating, wins, losses, last_choice_id, updated_at) VALUES (${sql(managerId)}, ${sql(type)}, ${sql(field(row, "Item ID", "itemId"))}, ${number(field(row, "Rating", "rating"), 1500)}, ${number(field(row, "Wins", "wins"))}, ${number(field(row, "Losses", "losses"))}, ${sql(field(row, "Last Choice ID", "lastChoiceId"))}, ${sql(field(row, "Updated At", "updatedAt") || new Date(0).toISOString())});`);
  eloCount += 1;
}

let choiceCount = 0;
const importedChoices = [];
for (const row of choiceResponse.choices || []) {
  const managerId = field(row, "Manager ID", "managerId"); const type = normalizedType(field(row, "Ranking Type", "rankingType"));
  if (!allowed(managerId, type)) continue;
  importedChoices.push({ managerId, type, winnerId: field(row, "Winner ID", "winnerId"), loserId: field(row, "Loser ID", "loserId"), createdAt: field(row, "Created At", "createdAt") });
  lines.push(`INSERT OR IGNORE INTO ranking_choices (choice_id, manager_id, ranking_type, item_a_id, item_b_id, winner_id, loser_id, created_at) VALUES (${sql(field(row, "ID", "id"))}, ${sql(managerId)}, ${sql(type)}, ${sql(field(row, "Item A ID", "itemAId"))}, ${sql(field(row, "Item B ID", "itemBId"))}, ${sql(field(row, "Winner ID", "winnerId"))}, ${sql(field(row, "Loser ID", "loserId"))}, ${sql(field(row, "Created At", "createdAt") || new Date(0).toISOString())});`);
  choiceCount += 1;
}

for (const groupKey of new Set(importedChoices.map((choice) => `${choice.managerId}:${choice.type}`))) {
  if (eloGroups.has(groupKey)) continue;
  const [managerId, type] = groupKey.split(":");
  const ratings = new Map();
  const stateFor = (itemId) => ratings.get(itemId) || { rating: 1500, wins: 0, losses: 0 };
  const groupChoices = importedChoices
    .filter((entry) => entry.managerId === managerId && entry.type === type)
    .sort((a, b) => String(a.createdAt).localeCompare(String(b.createdAt)));
  const reconstructedAt = groupChoices.at(-1)?.createdAt || new Date(0).toISOString();
  for (const choice of groupChoices) {
    const winner = { ...stateFor(choice.winnerId) }; const loser = { ...stateFor(choice.loserId) };
    const expectedWinner = 1 / (1 + 10 ** ((loser.rating - winner.rating) / 400));
    const expectedLoser = 1 / (1 + 10 ** ((winner.rating - loser.rating) / 400));
    winner.rating = Math.round(winner.rating + 64 * (1 - expectedWinner)); winner.wins += 1;
    loser.rating = Math.round(loser.rating + 64 * (0 - expectedLoser)); loser.losses += 1;
    ratings.set(choice.winnerId, winner); ratings.set(choice.loserId, loser);
  }
  for (const [itemId, state] of ratings) {
    lines.push(`INSERT OR REPLACE INTO ranking_elo (manager_id, ranking_type, item_id, rating, wins, losses, last_choice_id, updated_at) VALUES (${sql(managerId)}, ${sql(type)}, ${sql(itemId)}, ${state.rating}, ${state.wins}, ${state.losses}, '', ${sql(reconstructedAt)});`);
    eloCount += 1;
  }
}

for (const row of seedResponse.seeds || []) {
  const type = normalizedType(field(row, "Ranking Type", "rankingType"));
  if (!["games", "movies", "tv", "mcu"].includes(type)) continue;
  lines.push(`INSERT OR REPLACE INTO ranking_seeds (manager_id, ranking_type, item_id, seed_rank, seed_rating, seeded_at, reason) VALUES ('6', ${sql(type)}, ${sql(field(row, "Item ID", "itemId"))}, ${number(field(row, "Seed Rank", "seedRank"))}, ${number(field(row, "Seed Rating", "seedRating"), 1500)}, ${sql(field(row, "Seeded At", "seededAt") || new Date(0).toISOString())}, ${sql(field(row, "Reason", "reason"))});`);
}

const snapshotIds = new Set();
for (const row of snapshotResponse.snapshots || []) {
  const managerId = field(row, "Manager ID", "managerId"); const type = normalizedType(field(row, "Ranking Type", "rankingType"));
  if (!allowed(managerId, type)) continue;
  const id = field(row, "Snapshot ID", "snapshotId", "ID"); snapshotIds.add(id);
  lines.push(`INSERT OR REPLACE INTO ranking_snapshots (snapshot_id, manager_id, ranking_type, created_at, label, reason, source) VALUES (${sql(id)}, ${sql(managerId)}, ${sql(type)}, ${sql(field(row, "Created At", "createdAt") || new Date(0).toISOString())}, ${sql(field(row, "Label", "label"))}, ${sql(field(row, "Reason", "reason"))}, ${sql(field(row, "Source", "source"))});`);
}
for (const row of snapshotResponse.snapshotItems || []) {
  const snapshotId = field(row, "Snapshot ID", "snapshotId"); if (!snapshotIds.has(snapshotId)) continue;
  lines.push(`INSERT OR REPLACE INTO ranking_snapshot_items (snapshot_id, item_id, item_name, rank, rating, wins, losses, games) VALUES (${sql(snapshotId)}, ${sql(field(row, "Item ID", "itemId"))}, ${sql(field(row, "Item Name", "itemName", "Name"))}, ${number(field(row, "Rank", "rank"))}, ${number(field(row, "Rating", "rating"), 1500)}, ${number(field(row, "Wins", "wins"))}, ${number(field(row, "Losses", "losses"))}, ${number(field(row, "Games", "games"))});`);
}
for (const row of exclusionResponse.exclusions || []) {
  const managerId = field(row, "Manager ID", "managerId"); const type = normalizedType(field(row, "Ranking Type", "rankingType"));
  if (!allowed(managerId, type)) continue;
  lines.push(`INSERT OR REPLACE INTO ranking_exclusions (manager_id, ranking_type, item_id, excluded, updated_at) VALUES (${sql(managerId)}, ${sql(type)}, ${sql(field(row, "Item ID", "itemId"))}, ${truthy(field(row, "Excluded", "excluded")) ? 1 : 0}, ${sql(field(row, "Updated At", "updatedAt") || new Date(0).toISOString())});`);
}
for (const managerId of ["5", "6", "7"]) lines.push(`INSERT OR IGNORE INTO ranking_revisions (manager_id, ranking_type, revision) VALUES (${sql(managerId)}, 'mcu', 0);`);
for (const type of ["games", "movies", "tv"]) lines.push(`INSERT OR IGNORE INTO ranking_revisions (manager_id, ranking_type, revision) VALUES ('6', ${sql(type)}, 0);`);
lines.push("");
await writeFile(OUTPUT, lines.join("\n"), "utf8");
console.log(`Generated migration: ${itemCount} owned items, ${eloCount} Elo rows, ${choiceCount} choices, ${snapshotIds.size} snapshots.`);

async function loadJson(action) { const response = await fetch(`${ENDPOINT}?action=${encodeURIComponent(action)}`, { signal: AbortSignal.timeout(20000) }); if (!response.ok) throw new Error(`${action} returned ${response.status}`); const value = await response.json(); if (!value.ok) throw new Error(value.error || `${action} failed`); return value; }
async function loadCsv(url) { const response = await fetch(url, { signal: AbortSignal.timeout(20000) }); if (!response.ok) throw new Error(`Sheet returned ${response.status}`); return parseCsv(await response.text()); }
function parseCsv(text) { const matrix=[]; let row=[],value="",quoted=false; for(let i=0;i<text.length;i+=1){const c=text[i]; if(c==='"'&&quoted&&text[i+1]==='"'){value+='"';i+=1;}else if(c==='"')quoted=!quoted;else if(c===','&&!quoted){row.push(value);value="";}else if((c==='\n'||c==='\r')&&!quoted){if(c==='\r'&&text[i+1]==='\n')i+=1;row.push(value);if(row.some((cell)=>cell!==""))matrix.push(row);row=[];value="";}else value+=c;} row.push(value);if(row.some((cell)=>cell!==""))matrix.push(row);const headers=(matrix.shift()||[]).map((h)=>h.replace(/^\uFEFF/,"").trim());return matrix.map((values)=>Object.fromEntries(headers.map((h,i)=>[h,values[i]||""]))); }
function field(row, ...keys) { for (const key of keys) if (row?.[key] !== undefined && row[key] !== null) return clean(row[key]); return ""; }
function clean(value) { return String(value ?? "").trim(); }
function number(value, fallback=0) { const result=Number(value); return Number.isFinite(result) ? Math.round(result) : fallback; }
function truthy(value) { return ["1","true","yes","y","x"].includes(clean(value).toLowerCase()); }
function normalizedType(value) { const type=clean(value).toLowerCase(); return ({game:"games",movie:"movies",show:"tv"})[type] || type; }
function sql(value) { return `'${clean(value).replaceAll("'", "''")}'`; }
